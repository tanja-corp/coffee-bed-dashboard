const supportedLanguages = Object.keys(dictionaries);
let activeLanguage = 'en';

export function isSupportedLanguage(language) {
  return supportedLanguages.includes(language);
}

export function setLanguage(language) {
  activeLanguage = isSupportedLanguage(language) ? language : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = activeLanguage;
  return activeLanguage;
}

export function getLanguage() {
  return activeLanguage;
}

export function t(key, vars = {}) {
  const template = dictionaries[activeLanguage][key];
  if (template === undefined) return key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ));
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.setAttribute('title', t(element.dataset.i18nTitle));
  });
  document.title = t('page.title');
}
